def _render_caveats(results: dict[str, Any]) -> None:
    with st.expander("⚠️ Caveats, warnings & resilience logs", expanded=False):
        any_caveat = False
        for p in results.get("platforms", []):
            pc = p.get("caveats") or []
            if not pc:
                continue
            any_caveat = True
            st.markdown(f"**{p['platform']}** ({len(pc)} entries)")
            for c in pc:
                st.markdown(f"<div class='caveat-box'>{c}</div>", unsafe_allow_html=True)
        if not any_caveat:
            st.info("No caveats logged – all runs completed cleanly.")


def _render_summary(results: dict[str, Any]) -> None:
    st.header("1️⃣ Summary Matrix")
    df = _summary_matrix(results)
    if df.empty:
        st.warning("No platform data yet. Run `python main.py` first.")
        return

    # Pretty markdown table (sorted by 1-hop latency)
    show = df.copy()
    show = show.sort_values("1-hop p50 (ms)", na_position="last")
    st.markdown(show.to_markdown(index=False, floatfmt=".2f"))

    with st.expander("CSV download"):
        st.download_button(
            "Download matrix as CSV",
            data=df.to_csv(index=False).encode("utf-8"),
            file_name="summary_matrix.csv",
            mime="text/csv",
        )


def _render_ingest(results: dict[str, Any]) -> None:
    st.header("2️⃣ Ingestion Performance")
    df = _ingest_df(results)
    if df.empty:
        st.info("No ingestion data.")
        return

    col1, col2 = st.columns(2)
    with col1:
        fig = px.bar(
            df,
            x="Platform",
            y="Total Time (s)",
            color="Platform",
            text_auto=".2s",
            title="Total Ingestion Time (seconds)",
        )
        fig.update_layout(showlegend=False)
        st.plotly_chart(fig, use_container_width=True)
    with col2:
        fig2 = go.Figure()
        fig2.add_trace(
            go.Bar(
                x=df["Platform"],
                y=df["Nodes/sec"],
                name="Nodes/sec",
                offsetgroup=0,
                text=df["Nodes/sec"].apply(lambda v: f"{v:,.0f}"),
                textposition="outside",
            )
        )
        fig2.add_trace(
            go.Bar(
                x=df["Platform"],
                y=df["Rels/sec"],
                name="Rels/sec",
                offsetgroup=1,
                text=df["Rels/sec"].apply(lambda v: f"{v:,.0f}"),
                textposition="outside",
            )
        )
        fig2.update_layout(
            barmode="group",
            title="Throughput – Nodes & Rels per second",
            yaxis_title="Records / sec",
        )
        st.plotly_chart(fig2, use_container_width=True)


def _render_traversals(results: dict[str, Any]) -> None:
    st.header("3️⃣ Latency Distribution – 1-hop / 2-hop / 3-hop")
    df = _traversal_latency_df(results)
    if df.empty:
        st.info("No traversal latency data.")
        return

    fig = px.bar(
        df,
        x="Traversal",
        y="Latency (ms)",
        color="Statistic",
        barmode="group",
        facet_col="Platform",
        facet_col_wrap=2,
        text_auto=".1f",
        title="p50 vs p95 Traversal Latencies (ms) — grouped per platform",
    )
    fig.update_yaxes(matches=None, showticklabels=True)
    fig.update_layout(height=700)
    st.plotly_chart(fig, use_container_width=True)

    # Platform-agnostic comparison of p95 2-hop
    st.subheader("Ranking – 2-hop p95 (lower is better)")
    two_hop_p95 = df[(df["Traversal"] == "2-hop") & (df["Statistic"] == "p95")]
    two_hop_p95 = two_hop_p95.sort_values("Latency (ms)")
    if not two_hop_p95.empty:
        fig_rank = px.bar(
            two_hop_p95,
            x="Platform",
            y="Latency (ms)",
            color="Latency (ms)",
            color_continuous_scale="RdYlGn_r",
            text_auto=".1f",
        )
        st.plotly_chart(fig_rank, use_container_width=True)


def _render_cold_warm(results: dict[str, Any]) -> None:
    st.header("4️⃣ Cold vs Warm – Start-up Penalty")
    df = _cold_warm_df(results)
    if df.empty:
        st.info("No cold/warm comparison data.")
        return

    fig = make_subplots(
        rows=1,
        cols=2,
        subplot_titles=("Raw Latency (ms)", "Cold-over-Warm Penalty (%)"),
        column_widths=[0.6, 0.4],
    )
    platforms = df["Platform"].unique()
    workloads = df["Workload"].unique()
    colors = px.colors.qualitative.Plotly
    for i, wl in enumerate(workloads):
        s = df[df["Workload"] == wl]
        fig.add_trace(
            go.Bar(
                name=f"{wl} Cold",
                x=s["Platform"],
                y=s["Cold (ms)"],
                legendgroup=wl,
                marker_color=colors[i % len(colors)],
                opacity=0.55,
            ),
            row=1,
            col=1,
        )
        fig.add_trace(
            go.Bar(
                name=f"{wl} Warm p50",
                x=s["Platform"],
                y=s["Warm p50 (ms)"],
                legendgroup=wl,
                marker_color=colors[i % len(colors)],
            ),
            row=1,
            col=1,
        )
    penalty = df.groupby("Platform", as_index=False)["Penalty (%)"].mean()
    fig.add_trace(
        go.Bar(
            x=penalty["Platform"],
            y=penalty["Penalty (%)"],
            marker_color="indianred",
            text=penalty["Penalty (%)"].apply(lambda v: f"{v:+.1f}%"),
            textposition="outside",
            showlegend=False,
        ),
        row=1,
        col=2,
    )
    fig.update_layout(
        title="Cold-start effect across platforms & workloads",
        barmode="group",
        height=500,
    )
    st.plotly_chart(fig, use_container_width=True)


def _render_concurrency(results: dict[str, Any]) -> None:
    st.header("5️⃣ Concurrency Scaling – Sustained QPS")
    df = _concurrency_df(results)
    if df.empty:
        st.info("No concurrency sweep data.")
        return

    tab1, tab2 = st.tabs(["Total QPS", "Read / Write split"])
    with tab1:
        fig = px.line(
            df,
            x="Clients",
            y="QPS",
            color="Platform",
            markers=True,
            text=df["QPS"].apply(lambda v: f"{v:,.0f}"),
            title="Total QPS by client concurrency level (80/20 R/W)",
        )
        fig.update_traces(textposition="top center")
        fig.update_layout(xaxis=dict(type="category"))
        st.plotly_chart(fig, use_container_width=True)
    with tab2:
        fig2 = px.line(
            df,
            x="Clients",
            y="value",
            color="Platform",
            facet_row="variable",
            markers=True,
            title="Read QPS vs Write QPS split",
            data_frame=df.melt(
                id_vars=["Platform", "Clients"],
                value_vars=["Read QPS", "Write QPS"],
            ),
        )
        fig2.update_layout(yaxis=dict(title=None), height=700)
        fig2.update_layout(xaxis=dict(type="category"))
        st.plotly_chart(fig2, use_container_width=True)

    # Error counts table
    if df["Errors"].sum() > 0:
        st.subheader("Errors during concurrency sweeps")
        st.dataframe(
            df.pivot_table(
                index="Platform", columns="Clients", values="Errors", aggfunc="sum"
            ).fillna(0)
            .astype(int)
            .style.format(precision=0)
        )


def _render_metadata(results: dict[str, Any]) -> None:
    with st.expander("🧾 Metadata – Dataset / tunables / suite version", expanded=False):
        meta_col1, meta_col2 = st.columns(2)
        with meta_col1:
            st.subheader("Dataset")
            st.json(results.get("dataset", {}))
        with meta_col2:
            st.subheader("Tunables")
            st.json(results.get("tunables", {}))
        st.caption(
            f"Suite v{results.get('suite_version')} – generated "
            f"{results.get('generated_at', 'N/A')}"
        )


def main() -> None:
    st.title("📊 Graph Database Benchmark Suite")
    st.caption(
        "CognoDB Cloud · Neo4j AuraDB · TigerGraph · Memgraph · ArcadeDB — "
        "cold/warm latencies, true percentiles, and concurrency QPS sweeps."
    )

    results = _load_results()
    if results is None:
        st.error(
            "No `benchmark_results.json` found. Upload one in the sidebar or "
            "run `python main.py` first."
        )
        st.stop()

    # Header KPIs
    platforms = results.get("platforms", [])
    kpi1, kpi2, kpi3, kpi4 = st.columns(4)
    kpi1.metric("Platforms benchmarked", len(platforms))
    dataset = results.get("dataset", {})
    kpi2.metric("Dataset nodes", f"{dataset.get('nodes', 0):,}")
    kpi3.metric("Dataset edges", f"{dataset.get('relationships', 0):,}")
    qps_peak = max(
        (
            c["qps"]
            for p in platforms
            for c in p.get("concurrency", [])
        ),
        default=0,
    )
    kpi4.metric("Peak sustained QPS", f"{qps_peak:,.0f}")

    _render_summary(results)
    _render_ingest(results)
    _render_traversals(results)
    _render_cold_warm(results)
    _render_concurrency(results)
    _render_caveats(results)
    _render_metadata(results)


if __name__ == "__main__":
    main()
