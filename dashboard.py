# Data-frame builders
# ---------------------------------------------------------------------------


def _summary_matrix(results: dict[str, Any]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for p in results.get("platforms", []):
        lat = p.get("latencies") or {}
        t1 = (lat.get("traverse_1_hop") or {}).get("p50_ms")
        t2 = (lat.get("traverse_2_hop") or {}).get("p50_ms")
        t3 = (lat.get("traverse_3_hop") or {}).get("p50_ms")
        ingest = p.get("ingest") or {}
        conc = p.get("concurrency") or []
        qps_40 = next(
            (c["qps"] for c in conc if c["clients"] == 40), None
        )
        rows.append(
            {
                "Platform": p["platform"],
                "Status": p["status"],
                "Ingest Time (s)": round(ingest.get("total_time_sec", np.nan), 2)
                if ingest
                else np.nan,
                "Nodes/sec": int(ingest.get("nodes_per_sec", 0)) if ingest else 0,
                "Rels/sec": int(ingest.get("rels_per_sec", 0)) if ingest else 0,
                "Lookup p50 (ms)": round(
                    (lat.get("point_lookup") or {}).get("p50_ms", np.nan), 2
                ),
                "1-hop p50 (ms)": round(t1, 2) if t1 is not None else np.nan,
                "2-hop p50 (ms)": round(t2, 2) if t2 is not None else np.nan,
                "3-hop p50 (ms)": round(t3, 2) if t3 is not None else np.nan,
                "QPS @ 40c": round(qps_40, 1) if qps_40 is not None else np.nan,
                "Footprint": p.get("footprint", "N/A"),
            }
        )
    return pd.DataFrame(rows)


def _ingest_df(results: dict[str, Any]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for p in results.get("platforms", []):
        ing = p.get("ingest")
        if not ing:
            continue
        rows.append(
            {
                "Platform": p["platform"],
                "Total Time (s)": ing.get("total_time_sec", 0),
                "Nodes/sec": ing.get("nodes_per_sec", 0),
                "Rels/sec": ing.get("rels_per_sec", 0),
                "Batches": ing.get("batches_processed", 0),
            }
        )
    return pd.DataFrame(rows)


def _traversal_latency_df(results: dict[str, Any]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for p in results.get("platforms", []):
        lat = p.get("latencies") or {}
        for hop in (1, 2, 3):
            key = f"traverse_{hop}_hop"
            entry = lat.get(key) or {}
            for stat in ("p50_ms", "p95_ms"):
                rows.append(
                    {
                        "Platform": p["platform"],
                        "Traversal": f"{hop}-hop",
                        "Statistic": "p50" if stat == "p50_ms" else "p95",
                        "Latency (ms)": entry.get(stat, np.nan),
                    }
                )
    return pd.DataFrame(rows).dropna(subset=["Latency (ms)"])


def _cold_warm_df(results: dict[str, Any]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for p in results.get("platforms", []):
        lat = p.get("latencies") or {}
        for key, label in [
            ("point_lookup", "Point Lookup"),
            ("traverse_1_hop", "1-hop"),
            ("traverse_2_hop", "2-hop"),
            ("aggregate", "Aggregate"),
        ]:
            entry = lat.get(key) or {}
            cold = entry.get("cold_latency_ms")
            warm = entry.get("p50_ms")
            if cold is None or warm is None:
                continue
            penalty = (cold - warm) / warm * 100 if warm > 0 else np.nan
            rows.append(
                {
                    "Platform": p["platform"],
                    "Workload": label,
                    "Cold (ms)": cold,
                    "Warm p50 (ms)": warm,
                    "Penalty (%)": round(penalty, 1),
                }
            )
    return pd.DataFrame(rows)


def _concurrency_df(results: dict[str, Any]) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for p in results.get("platforms", []):
        for entry in p.get("concurrency", []):
            rows.append(
                {
                    "Platform": p["platform"],
                    "Clients": entry.get("clients"),
                    "QPS": entry.get("qps", 0),
                    "Read QPS": entry.get("read_qps", 0),
                    "Write QPS": entry.get("write_qps", 0),
                    "Errors": entry.get("errors", 0),
                }
            )
    return pd.DataFrame(rows)


